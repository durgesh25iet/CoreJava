package com.rays.string;

public class Switch {
	public static void main(String[]args) {
		
		String day = "Friday";
		
		switch (day) {
		case "Monday":
			System.out.println("Frist day of week");
			break;
		case "Tuesday":
			System.out.println("Secound day of week");
			break;
		case "Wednesday":
			System.out.println("Third day of week");
			break;
		case "Thrusday":
			System.out.println("Fourth day of week");
			break;
		case "Friday":
			System.out.println("Fifth day of week");
			break;
		case "Saturday":
			System.out.println("sixth day of week");
		default:
			System.out.println("aaj sunday hai");
			
		}
		
	}
	

}
