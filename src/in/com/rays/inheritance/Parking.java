package in.com.rays.inheritance;

public class Parking {

	private int id;
	private int area;
	private int parkingPrice;
	private int parkingNo;

	public void setId(int id) {
		this.id = id;
	}

	public int getID() {
		return id;
	}

	public void setArea(int area) {
		this.area = area;
	}

	public int getArea() {
		return area;
	}

	public void setParkingPrice(int parkingPrice) {
		this.parkingPrice = parkingPrice;
	}

	public int getParkingPrice() {
		return parkingPrice;
	}

	public void setParkingNO(int parkingNo) {
		this.parkingNo = parkingNo;
	}

	public int getParkingNO() {
		return parkingNo;
	}

}
