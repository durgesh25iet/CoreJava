package in.co.ray.string;

public class Teststringwithforloop {
	public static void main(String [ ]args) {
		String name = "Google";
		     
		
		
		for(int i = 0; i<name.length(); i++) {
			
			
			if(name.charAt(i)=='o') {
				System.out.println('o');	
	
			}else if (name.charAt(i)=='G')  {
				System.out.println('G');
			}
			
		}
		
	}
}
	
	

